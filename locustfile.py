import os
import random
from itertools import count

from locust import HttpUser, between, task


REQUEST_TYPES = ["INFO", "SCRIPT", "TOOL", "APP_PROJECT", "OTHER"]
REQUEST_PRIORITIES = ["LOW", "MEDIUM", "HIGH"]
REQUEST_STATUSES = ["NEW", "ACCEPTED", "IN_PROGRESS", "COMPLETED", "CLOSED", "REJECTED"]
_COUNTER = count(1)


class ApiUser(HttpUser):
    """
    Locust load profile for the DRF backend.
    Expected env vars:
      - LOCUST_USERNAME
      - LOCUST_PASSWORD
      - LOCUST_API_PREFIX (optional, default: /api)
    """

    wait_time = between(1, 4)

    def on_start(self):
        self.api_prefix = os.getenv("LOCUST_API_PREFIX", "/api").rstrip("/")
        self.username = os.getenv("LOCUST_USERNAME", "superadmin")
        self.password = os.getenv("LOCUST_PASSWORD", "test12345")

        self.headers = {}
        self.role_keys = set()
        self.source_prod_entities = []
        self.target_entities = []
        self._authenticate()
        self._bootstrap_context()

    def _authenticate(self):
        response = self.client.post(
            f"{self.api_prefix}/auth/login/",
            json={"username": self.username, "password": self.password},
            name="auth.login",
        )
        if response.status_code != 200:
            raise RuntimeError(f"Login failed ({response.status_code}): {response.text}")
        token = response.json().get("access")
        if not token:
            raise RuntimeError("Login succeeded but no access token returned.")
        self.headers = {"Authorization": f"Bearer {token}"}

    def _bootstrap_context(self):
        me_response = self.client.get(
            f"{self.api_prefix}/auth/me/",
            headers=self.headers,
            name="auth.me",
        )
        if me_response.status_code == 200:
            payload = me_response.json()
            self.role_keys = set(payload.get("role_keys") or [])

        entities_response = self.client.get(
            f"{self.api_prefix}/admin/entities/?page=1&page_size=1000",
            headers=self.headers,
            name="admin.entities",
        )
        entities = []
        if entities_response.status_code == 200:
            payload = entities_response.json()
            entities = payload.get("results") if isinstance(payload, dict) else payload
            if not isinstance(entities, list):
                entities = []

        self.source_prod_entities = [
            item for item in entities if item.get("entity_type") == "PROD"
        ]
        self.target_entities = [
            item for item in entities if item.get("entity_type") in {"SUPPORT", "TDEV"}
        ]

    @task(6)
    def list_requests(self):
        self.client.get(
            f"{self.api_prefix}/requests/?page=1&page_size=20",
            headers=self.headers,
            name="requests.list",
        )

    @task(4)
    def filter_by_status(self):
        status = random.choice(REQUEST_STATUSES)
        self.client.get(
            f"{self.api_prefix}/requests/?page=1&page_size=20&status={status}",
            headers=self.headers,
            name="requests.list.filtered_status",
        )

    @task(2)
    def dashboard(self):
        self.client.get(
            f"{self.api_prefix}/admin/dashboard/",
            headers=self.headers,
            name="admin.dashboard",
        )

    @task(2)
    def reports(self):
        self.client.get(
            f"{self.api_prefix}/admin/reports/",
            headers=self.headers,
            name="admin.reports",
        )

    @task(1)
    def create_request(self):
        if not self.target_entities:
            return

        target = random.choice(self.target_entities)
        payload = {
            "title": f"Load test request #{next(_COUNTER)}",
            "description": "Generated by Locust load test for API performance benchmarking.",
            "type": random.choice(REQUEST_TYPES),
            "priority": random.choice(REQUEST_PRIORITIES),
            "target_team": target["id"],
        }

        # API requires extra fields for higher roles.
        if "super_admin" in self.role_keys and self.source_prod_entities:
            source = random.choice(self.source_prod_entities)
            payload["company_id"] = source.get("company_id")
            payload["source_entity_id"] = source.get("id")
        elif "senior" in self.role_keys and self.source_prod_entities:
            source = random.choice(self.source_prod_entities)
            payload["source_entity_id"] = source.get("id")

        with self.client.post(
            f"{self.api_prefix}/requests/",
            json=payload,
            headers=self.headers,
            name="requests.create",
            catch_response=True,
        ) as response:
            if response.status_code in (200, 201):
                response.success()
            elif response.status_code in (400, 403):
                # Valid outcomes under role/permission constraints in load tests.
                response.success()
            else:
                response.failure(f"Unexpected status={response.status_code}, body={response.text[:250]}")

